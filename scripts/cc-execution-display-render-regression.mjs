async function launchBrowser() {
  try { return await chromium.launch() } catch (firstError) {
    for (const channel of ['chrome', 'msedge']) {
      try { return await chromium.launch({ channel }) } catch {}
    }
    throw firstError
  }
}

async function noOverflow(page, label) {
  const dimensions = await page.evaluate(() => ({ scrollWidth:document.documentElement.scrollWidth, clientWidth:document.documentElement.clientWidth }))
  assert.ok(dimensions.scrollWidth <= dimensions.clientWidth + 1, `${label}存在横向溢出：${JSON.stringify(dimensions)}`)
}

async function anyVisibleExact(locator, text) {
  return locator.getByText(text, { exact:true }).evaluateAll(nodes => nodes.some(node => {
    const style = getComputedStyle(node)
    return style.display !== 'none' && style.visibility !== 'hidden' && !!node.getClientRects().length
  }))
}

